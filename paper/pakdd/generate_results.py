def forced_top_one(runs_dir, expected_count, arms=tuple(arm for arm, *_ in ARMS)):
    """Ignore NONE and thresholds, breaking score ties by candidate row ID. Returns pooled and per-dataset accuracy."""
    matchable = {
        pool["instance_id"]: (pool["dataset"], [c["row_id"] for c in pool["candidates"]], set(pool["acceptable_row_ids"]))
        for pool in read_jsonl_gz(runs_dir / "cohorts/judge_eval_v2.jsonl.gz")
        if pool["partition"] == "test" and pool["acceptable_row_ids"]
    }
    if len(matchable) != expected_count:
        raise ValueError("Matchable test pools in the archived judge cohort differ from the locked count")
    accuracies, per_dataset = {}, {}
    for arm in arms:
        correct, totals = Counter(), Counter()
        seen = set()
        for prediction in read_jsonl_gz(runs_dir / f"preds/{arm}.jsonl.gz"):
            instance_id = prediction["instance_id"]
            if instance_id not in matchable:
                continue
            dataset, candidates, acceptable = matchable[instance_id]
            scores = prediction["probs"]
            if instance_id in seen or len(scores) != len(candidates) + 1:
                raise ValueError(f"Invalid candidate scores for {arm} on {instance_id}")
            winner = min(range(len(candidates)), key=lambda index: (-scores[index], candidates[index]))
            correct[dataset] += candidates[winner] in acceptable
            totals[dataset] += 1
            seen.add(instance_id)
        if len(seen) != expected_count:
            raise ValueError(f"Missing matchable test predictions for {arm}")
        accuracies[arm] = sum(correct.values()) / expected_count
        per_dataset[arm] = {dataset: correct[dataset] / totals[dataset] for dataset in totals}
    return accuracies, per_dataset


def split_mass_deferrals(runs_dir, primary, arm):
    """Matchable test pools that `arm` defers in scopes able to link, and those whose acceptable records together clear
    the select threshold and the NONE probability (probability split across several acceptable records)."""
    pools = {
        pool["instance_id"]: (pool["dataset"], [c["row_id"] for c in pool["candidates"]], set(pool["acceptable_row_ids"]))
        for pool in read_jsonl_gz(runs_dir / "cohorts/judge_eval_v2.jsonl.gz")
        if pool["partition"] == "test" and pool["acceptable_row_ids"]
    }
    deferred, multi, split, split_by_dataset, forced = 0, 0, 0, Counter(), 0
    for prediction in read_jsonl_gz(runs_dir / f"preds/{arm}.jsonl.gz"):
        if prediction["instance_id"] not in pools:
            continue
        dataset, rows, acceptable = pools[prediction["instance_id"]]
        policy = primary["thresholds"][f"{arm}/{dataset}"]
        # calibrated probabilities and decision exactly as scripts/mrd/21_evaluate.py and schema.decision_from_probs
        logits = [math.log(min(max(x, 1e-12), 1.0)) / policy["temperature"] for x in prediction["probs"]]
        top_logit = max(logits)
        weights = [math.exp(x - top_logit) for x in logits]
        probs = [w / sum(weights) for w in weights]
        k = len(rows)
        top = min(range(k), key=lambda j: (-probs[j], rows[j]))
        select = probs[top] >= policy["tau_select"] and probs[top] >= probs[k]
        if select or probs[k] >= policy["tau_none"]:
            continue
        if policy["tau_select"] > 1:
            forced += 1
            continue
        deferred += 1
        acceptable_idx = [j for j in range(k) if rows[j] in acceptable]
        multi += len(acceptable_idx) > 1
        mass = sum(probs[j] for j in acceptable_idx)
        if mass >= policy["tau_select"] and mass >= probs[k]:
            split += 1
            split_by_dataset[dataset] += 1
    return {"deferred": deferred, "forced": forced, "multi": multi, "split": split, "split_by_dataset": split_by_dataset}


